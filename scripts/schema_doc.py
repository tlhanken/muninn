"""Print Muninn's memory-interfaces contract as markdown, generated from parser.py.

This is what the vault's SCHEMA.md quotes. It is generated rather than written by hand
so the vault can never hold a third, drifting copy of the formats:

    just schema-doc

The parser is loaded by path, as the provider and the Tier 1 tests load it, so this
needs nothing but a Python interpreter.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

PARSER_PATH = Path(__file__).resolve().parents[1] / "src" / "muninn" / "parser.py"
SPEC = "openspec/specs/memory-interfaces/spec.md"


def _load_parser():
    spec = importlib.util.spec_from_file_location("muninn_parser_schema_doc", PARSER_PATH)
    assert spec is not None and spec.loader is not None, f"cannot load {PARSER_PATH}"
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _codes(values) -> str:
    return ", ".join(f"`{v}`" for v in values)


def render(p) -> str:
    rows = [
        ("Page types (`wiki_write` accepts only these)", _codes(p.PAGE_TYPES)),
        ("Confidence levels", f"{_codes(p.CONFIDENCE_LEVELS)} (default `{p.DEFAULT_CONFIDENCE}`)"),
        ("Statuses", f"{_codes(p.STATUSES)} (default `{p.DEFAULT_STATUS}`)"),
        ("Hidden from search", _codes(p.SEARCH_EXCLUDED_STATUSES)),
        ("Session log path", "`Episodic/sessions/session-<YYYY-MM-DD>-<sid8>.md`"),
        ("Session log type and tags",
         f"`{p.SESSION_LOG_TYPE}`; {_codes(p.SESSION_LOG_TAGS)}, `agent:<profile>`"),
        ("Session log fields", _codes(p.SESSION_LOG_FIELDS)),
        ("Session entry header",
         # `\|` keeps the pipe from splitting the table cell (GFM).
         "`### <YYYY-MM-DD HH:MM UTC> \\| User` or `\\| Assistant`, then the full message"),
    ]
    lines = [
        "<!-- Generated by `just schema-doc` from src/muninn/parser.py. Do not edit by hand. -->",
        "",
        "| Contract | Values |",
        "| --- | --- |",
        *(f"| {name} | {values} |" for name, values in rows),
        "",
        f"Authoritative definition: `{SPEC}` in the Muninn repository.",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    print(render(_load_parser()))
